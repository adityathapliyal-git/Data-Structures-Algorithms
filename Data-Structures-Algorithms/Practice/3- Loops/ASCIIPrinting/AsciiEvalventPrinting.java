public class AsciiEvalventPrinting {
    public static void main(String[] args) {
        char ch = 'A';
        int count = 0;
        System.out.println("ASCII values and their equivalent characters for 26 alphabets:");
        while (count < 26) {
            System.out.println("ASCII value of " + ch + " = " + (int)ch);
            ch++;
            count++;
        }
    }
}
